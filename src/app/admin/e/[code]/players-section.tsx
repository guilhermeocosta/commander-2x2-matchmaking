import { playerStatus } from "@/core/players";
import { getLatestRoundNumber, listEventPlayers } from "@/db/queries";
import type { EventRow } from "@/db/schema";
import { qrSvg, requestOrigin } from "@/lib/links";
import { getRoster } from "@/lib/roster";

import { AddPlayerForm, PlayerRow, type AdminPlayer } from "./players-admin";

/** The "Jogadores" section of the admin event panel. Rendered only after `requireAdmin()`. */
export async function PlayersSection({ event }: { event: EventRow }) {
  const [players, latestRound, roster, origin] = await Promise.all([
    listEventPlayers(event.id),
    getLatestRoundNumber(event.id),
    getRoster(),
    requestOrigin(),
  ]);
  const joinUrl = `${origin}/e/${event.code}`;
  const joinQr = await qrSvg(joinUrl);
  const rosterNames = new Map(roster.map((entry) => [entry.id, entry.name]));

  const rows: AdminPlayer[] = players.map((p) => ({
    id: p.id,
    displayName: p.displayName,
    rosterId: p.rosterId,
    rosterName: p.rosterId ? (rosterNames.get(p.rosterId) ?? null) : null,
    hasDevice: p.deviceTokenHash !== null,
    status: playerStatus(p, latestRound),
  }));
  const active = rows.filter((r) => r.status.kind !== "dropped").length;
  const takenRosterIds = players.flatMap((p) => (p.rosterId ? [p.rosterId] : []));

  return (
    <section id="jogadores" className="card bg-base-200">
      <div className="card-body gap-5">
        <div className="flex flex-wrap items-baseline justify-between gap-2">
          <h2 className="card-title">Jogadores</h2>
          <span className="text-sm text-base-content/70">
            {active} {active === 1 ? "ativo" : "ativos"} · {rows.length} no total
          </span>
        </div>

        <div className="flex flex-col items-center gap-3 rounded-box bg-base-100 p-4 sm:flex-row">
          <div
            className="w-40 shrink-0 overflow-hidden rounded-box [&>svg]:h-auto [&>svg]:w-full"
            role="img"
            aria-label={`QR code para ${joinUrl}`}
            // SVG markup generated by the qrcode package from our own URL.
            dangerouslySetInnerHTML={{ __html: joinQr }}
          />
          <div className="flex min-w-0 flex-col gap-1 text-center sm:text-left">
            <p className="text-sm text-base-content/70">Para entrar, os jogadores abrem:</p>
            <p className="font-mono text-lg font-bold break-all text-primary">
              {joinUrl.replace(/^https?:\/\//, "")}
            </p>
            <p className="text-sm text-base-content/70">
              ou digitam o código <strong className="font-mono">{event.code}</strong> na página
              inicial.
            </p>
          </div>
        </div>

        {roster.length === 0 && (
          <div role="status" className="alert alert-warning alert-soft text-sm">
            A lista de jogadores da temporada não carregou. Dá para entrar e adicionar pelo nome.
          </div>
        )}

        {rows.length === 0 ? (
          <p className="text-base-content/70">Ninguém entrou ainda.</p>
        ) : (
          <ul className="list rounded-box bg-base-100">
            {rows.map((player) => (
              <PlayerRow
                key={player.id}
                code={event.code}
                player={player}
                roster={roster}
                takenRosterIds={takenRosterIds}
              />
            ))}
          </ul>
        )}

        <details className="collapse-arrow collapse bg-base-100">
          <summary className="collapse-title font-medium">Adicionar jogador</summary>
          <div className="collapse-content">
            <AddPlayerForm code={event.code} roster={roster} takenRosterIds={takenRosterIds} />
          </div>
        </details>
      </div>
    </section>
  );
}
